/* ── Writes _redirects from the files in this repo ───────────────────
   The site is a static-assets Worker with html_handling = "none", so
   Cloudflare does no guessing: an address either names a file or it is
   a 404. GitHub Pages used to fill two gaps on its own, and every line
   this writes is a 200 REWRITE (the file is served at the address as
   typed, no redirect) that fills one of them:

     /               -> /index.html   ("none" also turns off the index lookup)
     /features       -> /features.html, one line per page
     /a/b@2x.webp    -> /a/b%402x.webp, one line per file whose name has a
                        character Workers stores percent-encoded. Without
                        it Cloudflare answers 307 to the encoded address,
                        which is every retina image on the site.

   Run it after adding, renaming or removing a page or an image:
     node tools/build-redirects.mjs
   Cloudflare's build runs it on every deploy too (see DEPLOYING.md), so a
   forgotten run can't ship a missing line. The same file lives in both
   repos (Semester-HQ-Site and student-dashboard); keep them identical.
──────────────────────────────────────────────────────────────── */
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

// Same matching as Wrangler's .assetsignore for the patterns used here:
// "dir", "dir/**", "file", "**/name".
const ignore = readFileSync(join(root, '.assetsignore'), 'utf8')
  .split('\n').map(s => s.trim()).filter(s => s && !s.startsWith('#'));
const ignored = (f) => ignore.some(p => {
  if (p.startsWith('**/')) return f.split('/').pop() === p.slice(3);
  const base = p.replace(/\/\*\*$/, '');
  return f === base || f.startsWith(base + '/');
});

// Files git knows about. Workers Builds deploys a clean clone, so this is
// exactly what production serves; untracked local files never count.
const files = execFileSync('git', ['-C', root, 'ls-files'], { encoding: 'utf8' })
  .split('\n').filter(f => f && !ignored(f) && !/^_(headers|redirects)$/.test(f));

const lines = [];
if (files.includes('index.html')) lines.push('/ /index.html 200');
for (const f of files.filter(f => f.endsWith('.html') && f !== '404.html').sort()) {
  lines.push(`/${f.slice(0, -5)} /${f} 200`);
}
for (const f of files.sort()) {
  const encoded = f.split('/').map(encodeURIComponent).join('/');
  if (encoded !== f) lines.push(`/${f} /${encoded} 200`);
}
// Workers allows 2,000 static rules; stop well before that.
if (lines.length > 1500) throw new Error(`${lines.length} redirect rules, close to Cloudflare's limit`);

const out = [
  '# Generated by tools/build-redirects.mjs. Do not edit by hand; run it instead.',
  '# Every line is a 200 rewrite: the address in the browser stays as typed.',
  '# See the comment at the top of that script for why each kind exists.',
  ...lines,
].join('\n') + '\n';

const path = join(root, '_redirects');
const before = existsSync(path) ? readFileSync(path, 'utf8') : '';
writeFileSync(path, out);
console.log(`_redirects: ${lines.length} rules${before === out ? ' (unchanged)' : ' (updated)'}`);
